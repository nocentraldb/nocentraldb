// The TypeScript SDK's texts in texts/texts.json (NOC-329, T3): entries of
// kind `ts`, the module scripts/texts.mjs generates from them,
// packages/sdk/src/texts.ts, and the gate's reading of packages/sdk/src.
// The bridge's own messages are the Rust SDK's entries since T3, so the
// gate reads crates/nocentraldb/src/bridge/ too.
import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { test } from "node:test";
import { fileURLToPath } from "node:url";
import {
  checkCode,
  checkEntries,
  generate,
  PATHS,
  rustFiles,
} from "./texts.mjs";
import {
  checkTsCode,
  generateTs,
  rfcErrorCodes,
  TS_PATHS,
} from "./texts-ts.mjs";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const read = (path) => readFileSync(join(ROOT, path), "utf8");
const file = (...texts) => ({ texts });

const TS = {
  id: "ts.databaseClosed",
  kind: "ts",
  code: "closed",
  text: "the database is closed",
  when: "Any call after db.close().",
};
const TS_FN = {
  id: "ts.notAField",
  kind: "ts",
  text: "{path}: not a field; declare it with a field function such as nc.string().",
  when: "ncdb model build, on a model whose field is not declared with a field function.",
};
const CODES = ["closed", "invalidValue", "lockOutOfDate"];

test("RFC 0009's error table gives the codes a ts text may carry", () => {
  const codes = rfcErrorCodes(read("docs/rfc/0009-sdk-api.md"));
  for (const code of ["closed", "notFound", "lockOutOfDate", "invalidValue"])
    assert.ok(codes.includes(code), code);
  assert.ok(!codes.includes("connection"), "a sync status field is no code");
});

test("a ts text passes with a code RFC 0009 lists, or with none", () => {
  assert.deepEqual(checkEntries(file(TS, TS_FN), [], [], CODES), []);
});

test("each broken ts text fails", () => {
  for (const [entry, why] of [
    [{ ...TS, code: "noSuchCode" }, "a code RFC 0009 does not list"],
    [{ ...TS, id: "error.databaseClosed" }, "the id of another kind"],
    [{ ...TS_FN, text: "{path:?}: not a field" }, "a Debug placeholder"],
    [{ ...TS, when: "" }, "no when"],
  ]) {
    assert.ok(
      checkEntries(file(entry), [], [], CODES).length > 0,
      `${why}: ${JSON.stringify(entry)}`,
    );
  }
});

test("the ts texts generate the TypeScript module: a constant per text, a function that fills placeholders, with when each shows", () => {
  const module = generateTs([
    TS,
    TS_FN,
    { ...TS, id: "error.closed", kind: "error" },
  ]);
  assert.match(module, /^\/\/ Generated by scripts\/texts\.mjs/);
  assert.match(
    module,
    /\/\*\* `databaseClosed` \(closed\): Any call after db\.close\(\)\. \*\/\nexport const DATABASE_CLOSED = "the database is closed";/,
  );
  assert.match(
    module,
    /export const notAField = \(path: unknown\): string =>\n {2}`\$\{path\}: not a field; declare it with a field function such as nc\.string\(\)\.`;/,
  );
  assert.equal(module.match(/export const/g).length, 2, "only ts texts");
});

const MODULE = "packages/sdk/src/texts.ts";
const USES = [
  "packages/sdk/src/db.ts",
  'throw new NcError("closed", texts.DATABASE_CLOSED);\nthrow new Error(texts.notAField(path));',
];
const check = (files, texts = [TS, TS_FN]) => checkTsCode(files, MODULE, texts);

test("TypeScript code that uses its texts passes", () => {
  assert.deepEqual(check([USES, [MODULE, "x"]]), []);
});

test("a text written in the TypeScript SDK's code fails, in each of its forms", () => {
  for (const [source, what] of [
    ['throw new NcError("closed", "the database is closed");', "an nc.Error"],
    // biome-ignore lint/suspicious/noTemplateCurlyInString: TypeScript source with a template, as the check reads it.
    ["throw new NcError(\n  code,\n  `no ${what} here`,\n);", "an nc.Error"],
    ['throw new Error("not a query");', "an error"],
    // biome-ignore lint/suspicious/noTemplateCurlyInString: TypeScript source with a template, as the check reads it.
    ["throw new Error(`${path}: not a field`);", "an error"],
    [
      'failure(request.id, "storageFailed", "the tab closed");',
      "an answer's error",
    ],
  ]) {
    const problems = check([USES, ["packages/sdk/src/x.ts", source]]);
    assert.ok(
      problems.some(
        (p) =>
          p.startsWith("packages/sdk/src/x.ts:") &&
          p.includes(`${what} written in code`),
      ),
      `${source}: ${problems}`,
    );
  }
});

test("a value passed on, such as the system's own error, is not a text", () => {
  assert.deepEqual(
    check([
      USES,
      [
        "packages/sdk/src/connect.ts",
        "failure(request.id, \"storageFailed\", String(error));\nnew NcError(error.code, error.message);\n// throw new Error('a comment');",
      ],
    ]),
    [],
  );
});

test("a ts text no code uses fails, and the generated module does not count", () => {
  assert.deepEqual(
    check([[MODULE, "texts.DATABASE_CLOSED texts.notAField("]]),
    [
      "ts.databaseClosed: no code uses texts.DATABASE_CLOSED",
      "ts.notAField: no code uses texts.notAField(",
    ],
  );
});

test("the TypeScript SDK's committed module is the one the texts generate", () => {
  const texts = JSON.parse(read(PATHS.texts)).texts;
  assert.equal(read(TS_PATHS.module), generateTs(texts));
});

test("the gate reads the bridge's code, whose messages are entries since T3", () => {
  const paths = rustFiles(join(ROOT, PATHS.rust)).map(([path]) => path);
  assert.ok(
    paths.some((path) => path.includes("/src/bridge/")),
    "a bridge file is read",
  );
  assert.ok(
    !paths.some((path) => path.includes("/bridge/tests/")),
    "the bridge's tests are not",
  );
});

const BRIDGE = {
  id: "error.bridgeNoSuchCall",
  kind: "error",
  code: "invalidValue",
  text: "no call {call}",
  when: "The bridge, given a call it does not know.",
};
const BRIDGE_CONST = {
  id: "error.bridgeOpenAlready",
  kind: "error",
  code: "invalidValue",
  text: "the database is open already",
  when: "The bridge's open, on a database it opened already.",
};
const NOT_FOUND = {
  id: "error.noSuchSpace",
  kind: "error",
  code: "notFound",
  text: "no such space",
  when: "db.spaces().get with a space the copy does not hold.",
};

test("the bridge's errors generate a file of their own, bridge.rs, without their prefix, and code names them as bridge::", () => {
  const files = generate([BRIDGE, BRIDGE_CONST, NOT_FOUND]);
  assert.match(files["mod.rs"], /pub\(crate\) mod bridge;/);
  assert.match(
    files["bridge.rs"],
    /pub\(crate\) fn no_such_call\(call: impl std::fmt::Display\) -> String/,
  );
  assert.match(files["bridge.rs"], /pub\(crate\) const OPEN_ALREADY: &str =/);
  assert.doesNotMatch(files["error.rs"], /OPEN_ALREADY|no_such_call/);
  assert.match(files["error.rs"], /NO_SUCH_SPACE/);
  const module = "crates/nocentraldb/src/texts";
  const uses = [
    "crates/nocentraldb/src/bridge/mod.rs",
    "texts::bridge::no_such_call(other) texts::bridge::OPEN_ALREADY texts::error::NO_SUCH_SPACE",
  ];
  assert.deepEqual(
    checkCode([uses], module, [BRIDGE, BRIDGE_CONST, NOT_FOUND]),
    [],
  );
});
