// The TypeScript SDK's texts (NOC-329, T3): entries of kind `ts` in
// texts/ts/, with a code when the SDK throws them as an nc.Error and
// none when the schema throws them as a plain Error that `ncdb model build`
// shows. scripts/texts.mjs generates packages/sdk/src/texts.ts from them, a
// constant per text or a function that fills its placeholders, and its
// gate reads packages/sdk/src with what is here:
//
// - a ts text's code is one RFC 0009's error table lists, as the TypeScript
//   SDK may throw a code the Rust SDK has no ErrorCode for (`lockOutOfDate`);
// - no text is written in the SDK's code outside the module: an nc.Error's
//   or an Error's message, or the error of a tab's answer (`failure`), given
//   a string or a template literal; a value passed on, such as the system's
//   own error, is no text;
// - every ts text is used, as `texts.NAME` or `texts.name(`.

import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { join, relative } from "node:path";
import { constName, placeholders } from "./texts.mjs";
import { mergeOrder } from "./texts-files.mjs";

/** Where the TypeScript SDK and its generated module live, relative to the root. */
export const TS_PATHS = {
  sdk: "packages/sdk/src",
  module: "packages/sdk/src/texts.ts",
  rfc: "docs/rfc/0009-sdk-api.md",
};

/** The codes of RFC 0009's error table: the rows of its "Errors" section. */
export const rfcErrorCodes = (source) => {
  const start = source.indexOf("\n## Errors\n");
  if (start < 0) return [];
  const end = source.indexOf("\n## ", start + 1);
  const section = source.slice(start, end < 0 ? undefined : end);
  // A row's first cell names one code or several: `a`, `b`, `c`.
  return [
    ...section.matchAll(
      /^\| (`[a-z][A-Za-z0-9]*`(?:, `[a-z][A-Za-z0-9]*`)*) \|/gm,
    ),
  ].flatMap(([, cell]) =>
    [...cell.matchAll(/`(\w+)`/g)].map(([, code]) => code),
  );
};

/** The name of a ts entry: its id after `ts.`. */
const nameOf = (entry) => entry.id.slice("ts.".length);

/** A TypeScript template literal of `text`, its placeholders filled. */
const template = (text) =>
  `\`${text
    .replace(/[\\`]/g, (c) => `\\${c}`)
    .replace(/\$\{/g, "\\${")
    // biome-ignore lint/suspicious/noTemplateCurlyInString: the generated template's placeholder, `${name}`.
    .replace(/\{(\w+)\}/g, "${$1}")}\``;

/** The TypeScript SDK's module of the ts texts, packages/sdk/src/texts.ts. */
export const generateTs = (texts) => {
  const out = [
    "// Generated by scripts/texts.mjs from texts/: do not edit.",
    "// Change a text there, then run `node scripts/texts.mjs --write`.",
    "//",
    "// Every text a developer reads from the TypeScript SDK (NOC-329, T3).",
    "// Each text's comment says when it shows. Internal: the package's entry",
    "// does not reach it.",
  ];
  for (const entry of mergeOrder(texts).filter((t) => t.kind === "ts")) {
    const code = entry.code ? ` (${entry.code})` : "";
    out.push("", `/** \`${nameOf(entry)}\`${code}: ${entry.when} */`);
    const params = placeholders(entry.text).map(([name]) => name);
    if (params.length === 0) {
      out.push(
        `export const ${constName(nameOf(entry))} = ${JSON.stringify(entry.text)};`,
      );
    } else {
      out.push(
        `export const ${nameOf(entry)} = (${params.map((p) => `${p}: unknown`).join(", ")}): string =>`,
        `  ${template(entry.text)};`,
      );
    }
  }
  return `${out.join("\n")}\n`;
};

/** A string or a template literal. */
const LITERAL = "[\"'`]";

/** Texts written in the TypeScript SDK's code, each with what it is. */
export const TS_STRAYS = [
  [
    new RegExp(
      String.raw`\bnew NcError\(\s*[^,()]+(?:\([^()]*\))?\s*,\s*${LITERAL}`,
      "g",
    ),
    "an nc.Error",
  ],
  [new RegExp(String.raw`\bnew Error\(\s*${LITERAL}`, "g"), "an error"],
  [
    new RegExp(String.raw`\bfailure\(\s*[^,()]+,\s*[^,()]+,\s*${LITERAL}`, "g"),
    "an answer's error",
  ],
];

/** How the SDK's code names a ts text: `texts.NAME` or `texts.name(`. */
export const tsUse = (entry) =>
  placeholders(entry.text).length === 0
    ? `texts.${constName(nameOf(entry))}`
    : `texts.${nameOf(entry)}(`;

/** Comment lines blanked out, as the stray check does not read them. */
const uncommented = (source) =>
  source
    .split("\n")
    .map((line) => (/^\s*(\/\/|\*|\/\*)/.test(line) ? "" : line))
    .join("\n");

/** The problems of the TypeScript SDK's code: stray texts, and ts texts no code uses. */
export const checkTsCode = (files, module, texts) => {
  const problems = [];
  const code = files.filter(([path]) => path !== module);
  for (const [path, original] of code) {
    const source = uncommented(original);
    for (const [pattern, what] of TS_STRAYS) {
      for (const match of source.matchAll(pattern)) {
        const line = source.slice(0, match.index).split("\n").length;
        problems.push(
          `${path}:${line}: ${what} written in code; add it to texts/ and use ./texts.ts`,
        );
      }
    }
  }
  const all = code.map(([, source]) => source).join("\n");
  for (const entry of texts.filter((t) => t.kind === "ts")) {
    const used = tsUse(entry);
    if (!all.includes(used)) problems.push(`${entry.id}: no code uses ${used}`);
  }
  return problems;
};

/** Every non-test .ts file under `dir`, as [path, source]. */
const tsFiles = (dir) => {
  const out = [];
  for (const name of readdirSync(dir)) {
    const path = join(dir, name);
    if (statSync(path).isDirectory()) out.push(...tsFiles(path));
    else if (name.endsWith(".ts") && !name.endsWith(".test.ts"))
      out.push([path, readFileSync(path, "utf8")]);
  }
  return out;
};

/** The gate's part for the TypeScript SDK in the repository at `root`: writes the module when `write`, and answers the problems. */
export const tsGate = (root, texts, write) => {
  const problems = [];
  const generated = generateTs(texts);
  const module = join(root, TS_PATHS.module);
  if (write) writeFileSync(module, generated);
  let committed = null;
  try {
    committed = readFileSync(module, "utf8");
  } catch {}
  if (committed !== generated)
    problems.push(
      `${TS_PATHS.module} differs from texts/: run node scripts/texts.mjs --write`,
    );
  const files = tsFiles(join(root, TS_PATHS.sdk)).map(([p, s]) => [
    relative(root, p),
    s,
  ]);
  problems.push(...checkTsCode(files, TS_PATHS.module, texts));
  return problems;
};
