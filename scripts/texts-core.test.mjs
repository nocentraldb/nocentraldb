// The core's texts in texts/texts.json (NOC-329, T6): entries of kind
// `core`, the module scripts/texts.mjs generates from them,
// crates/ncdb-core/src/texts.rs, and the gate's reading of the core's code.
import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { test } from "node:test";
import { fileURLToPath } from "node:url";
import { checkEntries, generate, generateCli } from "./texts.mjs";
import {
  CORE_PATHS,
  checkCoreCode,
  coreFiles,
  generateCore,
} from "./texts-core.mjs";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const read = (path) => readFileSync(join(ROOT, path), "utf8");
const file = (...texts) => ({ texts });

const CORE = {
  id: "core.refusalUndeprecated",
  kind: "core",
  text: "{collection}.{field}: no longer deprecated.\nKeep it deprecated, and add a new field instead.",
  when: "`ncdb model build`, when a deprecated field is no longer deprecated.",
};
const CORE_CONST = {
  id: "core.nameKindComputed",
  kind: "core",
  text: "computed field",
  when: "In core.refusalBadName, for a computed field's name.",
};
const CORE_BRACES = {
  id: "core.refusalUnmarkedPersonal",
  kind: "core",
  text: 'Keep .personal({{ person: "{person}" }}).',
  when: "`ncdb model build`, when a personal field is no longer personal.",
};
const REFUSAL = "crates/ncdb-core/src/model_lock/refusal.rs";
const USES = [
  REFUSAL,
  "texts::refusal_undeprecated(c, f)\nNameKind::Computed => texts::NAME_KIND_COMPUTED,",
];

test("a core text passes without a code, and fails with one", () => {
  assert.deepEqual(checkEntries(file(CORE, CORE_CONST), []), []);
  assert.ok(checkEntries(file({ ...CORE, code: "lockRefused" }), []).length);
  assert.ok(
    checkEntries(file({ ...CORE, id: "cli.refusalUndeprecated" }), []).length,
  );
});

test("a core text writes a brace as Rust does, doubled; a single one still fails", () => {
  assert.deepEqual(checkEntries(file(CORE_BRACES), []), []);
  assert.ok(
    checkEntries(file({ ...CORE_BRACES, text: "Keep .personal({ x })." }), [])
      .length,
  );
  assert.ok(
    checkEntries(
      file({ ...CORE_BRACES, kind: "ts", id: "ts.unmarkedPersonal" }),
      [],
      [],
      [],
    ).some((p) => p.includes("brace")),
    "the TypeScript module does not read Rust's escapes",
  );
});

test("the core texts generate the core's module, not the SDK's or the command line's", () => {
  const module = generateCore([CORE, CORE_CONST, CORE_BRACES]);
  assert.match(module, /^\/\/ Generated by scripts\/texts\.mjs/);
  assert.match(
    module,
    /pub\(crate\) fn refusal_undeprecated\(collection: impl std::fmt::Display, field: impl std::fmt::Display\) -> String \{\n {4}format!\("\{collection\}\.\{field\}: no longer deprecated\.\\u\{a\}Keep it/,
  );
  assert.match(
    module,
    /pub\(crate\) const NAME_KIND_COMPUTED: &str =\n {4}"computed field";/,
  );
  assert.match(
    module,
    /format!\("Keep \.personal\(\{\{ person: \\"\{person\}\\" \}\}\)\."\)/,
  );
  assert.ok(!generateCli([CORE]).includes("refusal"));
  assert.ok(
    !Object.values(generate([CORE]))
      .join("")
      .includes("refusal"),
  );
});

test("a constant core text with doubled braces holds single ones", () => {
  const module = generateCore([
    { ...CORE_CONST, text: "write .personal({{ person }})" },
  ]);
  assert.match(module, /"write \.personal\(\{ person \}\)";/);
});

test("core code that uses its texts passes", () => {
  assert.deepEqual(checkCoreCode([USES], [CORE, CORE_CONST]), []);
});

test("a text written in the core's code fails; notation and comments do not", () => {
  const problems = checkCoreCode(
    [USES, [REFUSAL, '"The lock is older than the previous one".into(),']],
    [],
  );
  assert.ok(
    problems.some(
      (p) => p.startsWith(`${REFUSAL}:1:`) && p.includes("written in code"),
    ),
    String(problems),
  );
  const fine = [
    '    Some(c) => format!("{c}.{name}"),',
    '    // a comment that says "two words"',
    '    let x = "two words"; // notation',
  ].join("\n");
  assert.deepEqual(checkCoreCode([USES, [REFUSAL, fine]], []), []);
});

test("a core text no code uses fails, and the generated module does not count", () => {
  assert.deepEqual(
    checkCoreCode(
      [[CORE_PATHS.module, "texts::refusal_undeprecated NAME_KIND_COMPUTED"]],
      [CORE, CORE_CONST],
    ),
    [
      "core.refusalUndeprecated: no code uses /\\btexts::refusal_undeprecated\\b/",
      "core.nameKindComputed: no code uses texts::NAME_KIND_COMPUTED",
    ],
  );
});

test("the gate reads all of crates/ncdb-core/src, outside its tests", () => {
  const paths = coreFiles(ROOT).map(([path]) => path);
  for (const path of [
    REFUSAL,
    "crates/ncdb-core/src/seal.rs",
    "crates/ncdb-core/src/view/mod.rs",
    "crates/ncdb-core/src/membership/body.rs",
  ])
    assert.ok(paths.includes(path), path);
  assert.ok(!paths.some((path) => path.includes("/tests/")));
  assert.ok(!paths.some((path) => path.startsWith("crates/ncdb-core/tests")));
});

test("the core's committed module is the one the texts generate", () => {
  const texts = JSON.parse(read("texts/texts.json")).texts;
  assert.equal(read(CORE_PATHS.module), generateCore(texts));
});

test("the core writes no text in code", () => {
  const texts = JSON.parse(read("texts/texts.json")).texts;
  assert.deepEqual(
    checkCoreCode(
      coreFiles(ROOT),
      texts.filter((t) => t.kind === "core"),
    ),
    [],
  );
});
