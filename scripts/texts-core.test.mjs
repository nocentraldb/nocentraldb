// The core's texts in texts/core/ (NOC-329, T6): entries of kind
// `core`, the module scripts/texts.mjs generates from them,
// crates/ncdb-core/src/texts.rs, and the gate's reading of the core's code.
import assert from "node:assert/strict";
import { readdirSync, readFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { test } from "node:test";
import { fileURLToPath } from "node:url";
import { checkEntries, generate, generateCli } from "./texts.mjs";
import {
  CORE_PATHS,
  checkConcerns,
  checkCoreCode,
  coreFiles,
  generateCore,
} from "./texts-core.mjs";
import { readTexts } from "./texts-files.mjs";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const read = (path) => readFileSync(join(ROOT, path), "utf8");
const file = (...texts) => ({ texts });

const CORE = {
  id: "core.refusalUndeprecated",
  kind: "core",
  text: "{collection}.{field}: no longer deprecated.\nKeep it deprecated, and add a new field instead.",
  when: "`ncdb model build`, when a deprecated field is no longer deprecated.",
};
const CORE_CONST = {
  id: "core.nameKindComputed",
  kind: "core",
  text: "computed field",
  when: "In core.refusalBadName, for a computed field's name.",
};
const CORE_BRACES = {
  id: "core.refusalUnmarkedPersonal",
  kind: "core",
  text: 'Keep .personal({{ person: "{person}" }}).',
  when: "`ncdb model build`, when a personal field is no longer personal.",
};
const REFUSAL = "crates/ncdb-core/src/model_lock/refusal.rs";
const USES = [
  REFUSAL,
  "texts::refusal_undeprecated(c, f)\nNameKind::Computed => texts::NAME_KIND_COMPUTED,",
];

test("a core text passes without a code, and fails with one", () => {
  assert.deepEqual(checkEntries(file(CORE, CORE_CONST), []), []);
  assert.ok(checkEntries(file({ ...CORE, code: "lockRefused" }), []).length);
  assert.ok(
    checkEntries(file({ ...CORE, id: "cli.refusalUndeprecated" }), []).length,
  );
});

test("a core text writes a brace as Rust does, doubled; a single one still fails", () => {
  assert.deepEqual(checkEntries(file(CORE_BRACES), []), []);
  assert.ok(
    checkEntries(file({ ...CORE_BRACES, text: "Keep .personal({ x })." }), [])
      .length,
  );
  assert.ok(
    checkEntries(
      file({ ...CORE_BRACES, kind: "ts", id: "ts.unmarkedPersonal" }),
      [],
      [],
      [],
    ).some((p) => p.includes("brace")),
    "the TypeScript module does not read Rust's escapes",
  );
});

test("the core texts generate the core's module, not the SDK's or the command line's", () => {
  const files = generateCore([CORE, CORE_CONST, CORE_BRACES]);
  assert.deepEqual(Object.keys(files).sort(), ["lock.rs", "mod.rs"]);
  const module = files["lock.rs"];
  assert.match(module, /^\/\/ Generated by scripts\/texts\.mjs/);
  assert.match(
    module,
    /pub\(crate\) fn refusal_undeprecated\(collection: impl std::fmt::Display, field: impl std::fmt::Display\) -> String \{\n {4}format!\("\{collection\}\.\{field\}: no longer deprecated\.\\u\{a\}Keep it/,
  );
  assert.match(
    module,
    /pub\(crate\) const NAME_KIND_COMPUTED: &str =\n {4}"computed field";/,
  );
  assert.match(
    module,
    /format!\("Keep \.personal\(\{\{ person: \\"\{person\}\\" \}\}\)\."\)/,
  );
  assert.ok(!generateCli([CORE]).includes("refusal"));
  assert.ok(
    !Object.values(generate([CORE]))
      .join("")
      .includes("refusal"),
  );
});

test("one file per concern, which mod.rs re-exports, so code names a text texts::NAME", () => {
  const files = generateCore([
    CORE,
    { ...CORE_CONST, id: "core.viewModel", text: "the view was folded" },
    { ...CORE_CONST, id: "core.pairingReadLink", text: "its link byte" },
  ]);
  assert.deepEqual(Object.keys(files).sort(), [
    "account.rs",
    "lock.rs",
    "mod.rs",
    "view.rs",
  ]);
  assert.match(files["view.rs"], /const VIEW_MODEL/);
  assert.match(files["account.rs"], /const PAIRING_READ_LINK/);
  for (const concern of ["account", "lock", "view"])
    assert.match(
      files["mod.rs"],
      new RegExp(`mod ${concern};\\npub\\(crate\\) use ${concern}::\\*;`),
    );
});

test("a core text whose name begins with no concern's word fails", () => {
  assert.deepEqual(checkConcerns([CORE, CORE_CONST]), []);
  assert.deepEqual(
    checkConcerns([{ ...CORE_CONST, id: "core.somethingElse" }]),
    [
      "core.somethingElse: its name begins with no concern's word; add the word to CONCERNS in scripts/texts-core.mjs",
    ],
  );
});

test("a constant core text with doubled braces holds single ones", () => {
  const module = Object.values(
    generateCore([{ ...CORE_CONST, text: "write .personal({{ person }})" }]),
  ).join("");
  assert.match(module, /"write \.personal\(\{ person \}\)";/);
});

test("core code that uses its texts passes", () => {
  assert.deepEqual(checkCoreCode([USES], [CORE, CORE_CONST]), []);
});

test("a text written in the core's code fails; notation and comments do not", () => {
  const problems = checkCoreCode(
    [USES, [REFUSAL, '"The lock is older than the previous one".into(),']],
    [],
  );
  assert.ok(
    problems.some(
      (p) => p.startsWith(`${REFUSAL}:1:`) && p.includes("written in code"),
    ),
    String(problems),
  );
  const fine = [
    '    Some(c) => format!("{c}.{name}"),',
    '    // a comment that says "two words"',
    '    let x = "two words"; // notation',
  ].join("\n");
  assert.deepEqual(checkCoreCode([USES, [REFUSAL, fine]], []), []);
});

test("a core text no code uses fails, and the generated module does not count", () => {
  assert.deepEqual(
    checkCoreCode(
      [
        [
          `${CORE_PATHS.module}/lock.rs`,
          "texts::refusal_undeprecated NAME_KIND_COMPUTED",
        ],
      ],
      [CORE, CORE_CONST],
    ),
    [
      "core.refusalUndeprecated: no code uses /\\btexts::refusal_undeprecated\\b/",
      "core.nameKindComputed: no code uses texts::NAME_KIND_COMPUTED",
    ],
  );
});

test("the gate reads all of crates/ncdb-core/src, outside its tests", () => {
  const paths = coreFiles(ROOT).map(([path]) => path);
  for (const path of [
    REFUSAL,
    "crates/ncdb-core/src/seal.rs",
    "crates/ncdb-core/src/view/mod.rs",
    "crates/ncdb-core/src/membership/body.rs",
  ])
    assert.ok(paths.includes(path), path);
  assert.ok(!paths.some((path) => path.includes("/tests/")));
  assert.ok(!paths.some((path) => path.startsWith("crates/ncdb-core/tests")));
});

test("the core's committed module is the one the texts generate", () => {
  const texts = readTexts(ROOT).texts;
  const generated = generateCore(texts);
  assert.deepEqual(
    readdirSync(join(ROOT, CORE_PATHS.module)).sort(),
    Object.keys(generated).sort(),
  );
  for (const [name, content] of Object.entries(generated))
    assert.equal(read(`${CORE_PATHS.module}/${name}`), content, name);
});

test("the core writes no text in code", () => {
  const texts = readTexts(ROOT).texts;
  assert.deepEqual(
    checkCoreCode(
      coreFiles(ROOT),
      texts.filter((t) => t.kind === "core"),
    ),
    [],
  );
});

test("an inline test module is no code the gate reads", () => {
  const source = [
    "fn f() -> &str { texts::NAME_KIND_COMPUTED }",
    "",
    "#[cfg(test)]",
    "mod tests {",
    "    fn g() {",
    '        let _ = "a text in a test";',
    "    }",
    "}",
    "",
    'fn h() { let _ = "after the tests"; }',
  ].join("\n");
  const problems = checkCoreCode([[REFUSAL, source]], [CORE_CONST]);
  assert.deepEqual(
    problems.map((p) => p.split(":")[1]),
    ["10"],
    String(problems),
  );
});

test("a panic's message is no text: it describes a bug in the core", () => {
  const source = [
    'let a = x.expect("the log holds the change");',
    "let b = y",
    "    .expect(",
    '        "32 bytes are far below the limit",',
    "    );",
    'unreachable!("a genesis node")',
    'assert_ne!(number, 0, "the first account key is number 1");',
    'assert!(ok, "it holds here");',
    'assert_eq!(a, b, "they are equal");',
    'panic!("the core broke here")',
  ].join("\n");
  assert.deepEqual(checkCoreCode([[REFUSAL, source]], []), []);
  assert.ok(
    checkCoreCode([[REFUSAL, 'Err(Problem::new("this is a text"))']], [])
      .length,
  );
});

test("a word in the core's code needs a lower-case letter, so SQL is no text", () => {
  const source = [
    '"SELECT frame FROM log WHERE space_id = ?1 ORDER BY local_position"',
    'format!("({name} IS NOT NULL OR ({name} IS NULL AND {rest}))")',
    'format!("EXPLAIN QUERY PLAN {sql}")',
  ].join("\n");
  assert.deepEqual(checkCoreCode([[REFUSAL, source]], []), []);
  for (const text of [
    '"SQLite failed: {error}"',
    '"OPFS could not be opened"',
    '"select frame from log"',
  ])
    assert.ok(checkCoreCode([[REFUSAL, text]], []).length, text);
});

test("a text continued over lines with a backslash is a text written in code", () => {
  const source = [
    "format!(",
    '    "format {format} is not known to this version; \\',
    '     Build the lock with the matching version of ncdb."',
    ")",
  ].join("\n");
  const problems = checkCoreCode([[REFUSAL, source]], []);
  assert.deepEqual(
    problems.map((p) => p.split(":")[1]),
    ["2"],
    String(problems),
  );
});
