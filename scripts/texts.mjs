#!/usr/bin/env node
// Every text a developer reads from the SDKs lives in texts/texts.json
// (NOC-329; the owner's decision of 2026-11-15). This script generates the
// Rust module the SDK reads them from, crates/nocentraldb/src/texts.rs, and
// checks for the gate (task repo:texts):
//
// - the file: each entry has an id, a kind, a code, a text, when it shows and
//   the release it first appeared in; ids are unique; a code is one the SDK
//   has (NoticeCode), and every NoticeCode has its notice;
// - the generated module equals what this script writes from the file;
// - no notice text is written in the SDK's code outside the generated
//   module: a `text:` followed by a string literal fails;
// - every text is used outside the generated module.
//
// `node scripts/texts.mjs --write` regenerates the module after an edit;
// `node scripts/texts.mjs --check` is the gate.

import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";
import { parseArgs } from "node:util";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");

/** Where the texts and the SDK live, relative to the root; tests point elsewhere. */
export const PATHS = {
  texts: "texts/texts.json",
  rust: "crates/nocentraldb/src",
  module: "crates/nocentraldb/src/texts.rs",
  noticeCodes: "crates/nocentraldb/src/members/notice.rs",
};

const KINDS = ["notice"];
const FIELDS = ["id", "kind", "code", "text", "when", "since"];
const CODE = /^[a-z][A-Za-z0-9]*$/;
const SINCE = /^(unreleased|\d+\.\d+\.\d+(-beta\.\d+)?)$/;

/** `memberAdded` → `MEMBER_ADDED`. */
export const constName = (code) =>
  code.replace(/([a-z0-9])([A-Z])/g, "$1_$2").toUpperCase();

/** `memberAdded` → `MemberAdded`, the Rust variant. */
const variant = (code) => code[0].toUpperCase() + code.slice(1);

/** A Rust string literal of `text`. */
const rustString = (text) => {
  let out = '"';
  for (const c of text) {
    const n = c.codePointAt(0);
    if (c === '"') out += '\\"';
    else if (c === "\\") out += "\\\\";
    else if (n < 0x20 || n === 0x7f) out += `\\u{${n.toString(16)}}`;
    else out += c;
  }
  return `${out}"`;
};

/** A doc comment of `text`, wrapped at 76 columns after `prefix`. */
const doc = (text, prefix) => {
  const lines = [];
  let line = "";
  for (const word of text.split(/\s+/)) {
    if (line && line.length + 1 + word.length > 76) {
      lines.push(line);
      line = word;
    } else line = line ? `${line} ${word}` : word;
  }
  if (line) lines.push(line);
  return lines.map((l) => `${prefix}/// ${l}`).join("\n");
};

/** The Rust module the texts generate. */
export const generate = (texts) => {
  const out = [
    "// Generated by scripts/texts.mjs from texts/texts.json: do not edit.",
    "// Change a text there, then run `node scripts/texts.mjs --write`.",
    "",
    "//! Every text a developer reads from the SDK, from texts/texts.json",
    "//! (NOC-329). Each constant's comment says when it shows.",
    "",
  ];
  for (const kind of KINDS) {
    const entries = texts.filter((t) => t.kind === kind);
    if (entries.length === 0) continue;
    out.push(`/// The texts of [\`crate::Notice\`], by code.`);
    out.push(`pub(crate) mod ${kind} {`);
    entries.forEach((entry, i) => {
      if (i > 0) out.push("");
      out.push(
        doc(`\`${entry.code}\` (since ${entry.since}): ${entry.when}`, "    "),
      );
      out.push(`    pub(crate) const ${constName(entry.code)}: &str =`);
      out.push(`        ${rustString(entry.text)};`);
    });
    out.push("}");
  }
  return `${out.join("\n")}\n`;
};

/** The variants of `pub enum NoticeCode` in `source`. */
export const noticeVariants = (source) => {
  const body = source.match(/pub enum NoticeCode \{([\s\S]*?)\n\}/);
  if (!body) return [];
  return body[1]
    .split("\n")
    .map((line) => line.trim())
    .filter((line) => /^[A-Z][A-Za-z0-9]*,$/.test(line))
    .map((line) => line.slice(0, -1));
};

/** The problems of the file's entries, each a line. */
export const checkEntries = (file, variants) => {
  const problems = [];
  if (!file || !Array.isArray(file.texts)) {
    return ['texts.json: a "texts" array is required'];
  }
  const ids = new Set();
  for (const [i, entry] of file.texts.entries()) {
    const at = `texts[${i}]${entry?.id ? ` (${entry.id})` : ""}`;
    if (!entry || typeof entry !== "object") {
      problems.push(`${at}: not an object`);
      continue;
    }
    for (const field of FIELDS) {
      if (typeof entry[field] !== "string" || entry[field].trim() === "") {
        problems.push(`${at}: "${field}" must be a non-empty text`);
      }
    }
    for (const field of Object.keys(entry)) {
      if (!FIELDS.includes(field))
        problems.push(`${at}: unknown field "${field}"`);
    }
    if (typeof entry.id === "string") {
      if (ids.has(entry.id)) problems.push(`${at}: the id is used twice`);
      ids.add(entry.id);
    }
    if (typeof entry.kind === "string" && !KINDS.includes(entry.kind)) {
      problems.push(`${at}: kind must be one of ${KINDS.join(", ")}`);
    }
    if (typeof entry.code === "string") {
      if (!CODE.test(entry.code))
        problems.push(`${at}: the code must be camelCase`);
      else if (entry.id !== `${entry.kind}.${entry.code}`) {
        problems.push(`${at}: the id must be "${entry.kind}.${entry.code}"`);
      }
      if (entry.kind === "notice" && !variants.includes(variant(entry.code))) {
        problems.push(
          `${at}: NoticeCode has no variant ${variant(entry.code)}`,
        );
      }
    }
    if (typeof entry.since === "string" && !SINCE.test(entry.since)) {
      problems.push(
        `${at}: since must be "unreleased" or a beta or stable version`,
      );
    }
  }
  const notices = new Set(
    file.texts.filter((t) => t?.kind === "notice").map((t) => t.code),
  );
  for (const v of variants) {
    const code = v[0].toLowerCase() + v.slice(1);
    if (!notices.has(code))
      problems.push(`NoticeCode::${v} has no notice in texts.json`);
  }
  return problems;
};

/** Every non-test .rs file under `dir`, as [path, source]. */
const rustFiles = (dir) => {
  const out = [];
  for (const name of readdirSync(dir)) {
    const path = join(dir, name);
    if (statSync(path).isDirectory()) {
      if (name !== "tests") out.push(...rustFiles(path));
    } else if (name.endsWith(".rs") && !/(^|_)tests?\.rs$/.test(name)) {
      out.push([path, readFileSync(path, "utf8")]);
    }
  }
  return out;
};

/** A notice text written in code: `text:` and then a string literal. */
const STRAY = /\btext:\s*"/g;

/** The problems of the SDK's code: stray texts, and texts no code uses. */
export const checkCode = (files, module, texts) => {
  const problems = [];
  const code = files.filter(([path]) => path !== module);
  for (const [path, source] of code) {
    for (const match of source.matchAll(STRAY)) {
      const line = source.slice(0, match.index).split("\n").length;
      problems.push(
        `${path}:${line}: a notice text written in code; add it to texts/texts.json and use crate::texts`,
      );
    }
  }
  const all = code.map(([, source]) => source).join("\n");
  for (const entry of texts) {
    const name = `${entry.kind}::${constName(entry.code)}`;
    if (!all.includes(name))
      problems.push(`${entry.id}: no code uses texts::${name}`);
  }
  return problems;
};

const main = () => {
  const { values } = parseArgs({
    options: { check: { type: "boolean" }, write: { type: "boolean" } },
  });
  const at = (path) => join(ROOT, path);
  const file = JSON.parse(readFileSync(at(PATHS.texts), "utf8"));
  const variants = noticeVariants(readFileSync(at(PATHS.noticeCodes), "utf8"));
  const problems = checkEntries(file, variants);
  if (problems.length === 0) {
    const generated = generate(file.texts);
    if (values.write) writeFileSync(at(PATHS.module), generated);
    let committed = "";
    try {
      committed = readFileSync(at(PATHS.module), "utf8");
    } catch {}
    if (committed !== generated) {
      problems.push(
        `${PATHS.module} differs from texts/texts.json: run node scripts/texts.mjs --write`,
      );
    }
    const files = rustFiles(at(PATHS.rust)).map(([p, s]) => [
      relative(ROOT, p),
      s,
    ]);
    problems.push(...checkCode(files, PATHS.module, file.texts));
  }
  if (problems.length > 0) {
    for (const problem of problems) console.error(`texts: ${problem}`);
    process.exit(1);
  }
  if (!values.check && !values.write) {
    console.log(`${file.texts.length} texts in ${PATHS.texts}`);
  }
};

if (process.argv[1] === fileURLToPath(import.meta.url)) main();
